#!/usr/bin/env python3
"""Verdict (and optionally record) for the TRNG-interface flow run by run.sh.

Reads flow/build/trng_if/{if,sys,real}.json and the summaries. Fails (exit 1)
unless every simulation that ran passed. Without --check-only it also writes
an append-only record under verification/records/trng-if-sim/. Standard
library only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "flow/common"))
import record_lib as rc  # noqa: E402

EXPERIMENT = "trng-if-sim"
INPUTS = (
    "rtl/trng_if/trng_if.v",
    "rtl/trng_if/README.md",
    "rtl/drbg/ctr_drbg.v",
    "rtl/drbg/drbg_top.v",
    "rtl/aes/aes_core.v",
    "verification/rtl/trng_if/tb_trng_if.v",
    "verification/rtl/trng_if/tb_sys.v",
    "verification/rtl/trng_if/trngmodel.py",
    "verification/rtl/trng_if/test_trng_if.py",
    "verification/rtl/trng_if/test_sys.py",
    "verification/rtl/trng_if/mk_req.py",
    "verification/rtl/trng_if/fetch_trng.sh",
    "verification/rtl/trng_if/run.sh",
    "verification/rtl/trng_if/make_record.py",
    "flow/common/record_lib.py",
    "verification/model/ctr_drbg.py",
    "reuse.lock.json",
    "scripts/setup-env.sh",
)


def load(out: Path, name: str):
    p = out / name
    return json.loads(p.read_text()) if p.exists() else None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--check-only", action="store_true")
    args = ap.parse_args()
    out = args.out_dir
    runs = {"if": load(out, "if.json"), "sys": load(out, "sys.json"), "real": load(out, "real.json")}
    ran = {k: v for k, v in runs.items() if v}
    ok = bool(ran) and all(v["status"] == "pass" for v in ran.values()) and runs["if"] and runs["sys"]
    print("trng_if: " + " ".join(f"{k}={v['status']}" for k, v in ran.items()) +
          ("" if runs["real"] else " real=SKIPPED") + f" -> {'PASS' if ok else 'FAIL'}")
    if not ok:
        return 1
    if args.check_only:
        return 0

    rev = rc.require_clean_inputs(INPUTS[:-1])
    v = rc.tool_versions()
    sib = json.loads((rc.REPO / "reuse.lock.json").read_text())
    pin = next(i for i in sib["imports"] if i["from"] == "2AMLogic/sky130-trng")
    sib_sha = pin["files"][0]["sha256"]

    def summ(name):
        p = out / name
        return p.read_text().strip().replace("\n", " ; ") if p.exists() else "not run"

    real_txt = (f"{runs['real']['passed_count']}/{runs['real']['test_count']} tests passed on `trng_digital.v` fetched at "
                f"`{pin['commit']}` (sha256 `{sib_sha}` verified by `fetch_trng.sh` against `reuse.lock.json`). `{summ('summary-real.txt')}`"
                if runs["real"] else "**NOT RUN** (`--skip-real`): the end-to-end case against the sibling's RTL did not execute for this record.")
    meta = {"tool_versions": v}
    body = f"""- **Claim**: `rtl/trng_if/trng_if.v` implements this block's side of `spec/trng-interface.md` sections 3.1-3.4 (2-flop synchronizer on the 50 kHz sample clock with `t_rise`/`t_fall` ticks; coherent sampling of `out_data`/`out_valid`/`gated`/`startup_done`/`alarm` at `t_fall`; `out_ready` held exactly one sample period so exactly one word moves; a separate 2-flop `alarm` path to zeroize; a write-only bus sequencer with the three allowed transactions and `bus_re` tied 0), and `drbg_top` zeroizes the DRBG `Key`/`V`, working registers and seed buffer on a TRNG alarm. A simulation claim at the stated operating points; it says nothing about the sibling's entropy (provisional until silicon), about clock-domain timing (no STA was run: the half-period constraint is listed in `rtl/trng_if/README.md`), or about any property beyond the cases below.
- **Design provenance**: RTL, pre-synthesis simulation (Icarus). The sibling is modelled by a port-protocol stub (`trngmodel.py`: outputs change only just after a rising edge of the sample clock; pop when `out_ready && out_valid` at a rising edge; ALARM sticky until a W1C write; it does not mask `out_valid` when gated) and, in one bench, by the sibling's own RTL.
- **Run configuration**: `./scripts/setup-env.sh` then `./verification/rtl/trng_if/run.sh --record`. Requests are generated by `mk_req.py`; engine icarus, `random_seed` 1. Sample-clock periods are not a multiple of the core period (ratio*20 ns + 3 ns, 7 ns phase) so the two clocks drift against each other.
- **Benches and results**:
  - `trng_if` alone vs the stub, 40:1 ratio ({runs['if']['passed_count']}/{runs['if']['test_count']} tests passed, includes the 1000:1 collection case): bring-up writes (`CTRL = 0b011` once, nothing else), 16-word seed and 8-word reseed with exactly one pop per word and the seed equal to the popped words in arrival order, seed held with no further pops while ready and cleared on release, `gated` and `startup_done = 0` mid-seed (partial seed discarded, collection restarts from word 0), a one-period `gated` pulse, no word accepted when `gated` was high at the previous or current sample (checked by the stub from its own history), alarm: seed buffer zero within the bound and held zero with a request pending, `ALARM = 0b111` written only after zeroize completed, then `SOFT_RST` and re-enable, `alarm_zeroized` low again, a new seed collected, software zeroize. `{summ('summary-if.txt')}`
  - `drbg_top` vs the stub, reseed interval 3 ({runs['sys']['passed_count']}/{runs['sys']['test_count']} tests passed): instantiate/generate (128, 1024 and 40 bits)/reseed against `verification/model/ctr_drbg.py` using the words the stub saw popped; `RESEED_REQUIRED` at the interval and generate refused, also while `gated`; a reseed stalls while `gated` and completes on 8 clean words after ungating; an alarm during a running 1024-bit generate zeroizes Key, V, the df/Update working registers, the output register and the seed buffer within the bound, no block or `done` appears afterwards, the registers are held zero while the alarm is asserted, generate is then refused (not instantiated) until a re-instantiate, which matches the model. `{summ('summary-sys.txt')}`
  - `drbg_top` vs the sibling's RTL: {real_txt}
- **Negative controls** (`./verification/rtl/trng_if/run.sh --negative-control`): each of these corrupted builds makes the bench fail: ignoring the previous sample's gating (`TRNG_IF_NEG_PREV`), not discarding a partial seed (`TRNG_IF_NEG_DISCARD`), a seed one word short (`TRNG_IF_NEG_COUNT`), DRBG `V` surviving the alarm zeroize (`DRBG_NEG_ZEROIZE`), one request too many before `RESEED_REQUIRED` (`DRBG_NEG_INTERVAL`). There is no negative control for "ALARM written only after zeroize completed": at the stated ratio the sequencer's earliest write is hundreds of core cycles after the 3-cycle zeroize, so the ordering is checked but a bench cannot tell a sequencer that skips the wait from the shipped one.
- **Measured**: alarm pin to zeroize asserted and to Key/V/seed zero is checked against a 6-cycle bound (2 synchronizer cycles, 1 register, 1 clear, margin) in both benches; the formal bound is in the `drbg-trng-formal` record.
- **Not covered**: the sibling at its unshortened parameters (full 1024-sample start-up, 256-bit conditioner block); the `gated`-persists-then-`RESEED_REQUIRED` transition of `spec/target-spec.md` section 5 (no persistence threshold is specified, none is implemented); bus-visible status mirrors, key slots and the lifecycle FSM (issues #44 and #46); netlist-level behavior.
- **Tool versions**: {v['icarus']}, cocotb {v['cocotb']}, Python {v['python']}, klt pinned at `{v['klt_pin']}`, ciel {v['ciel']}.
- **Links**: `rtl/trng_if/`, `verification/rtl/trng_if/`, `spec/trng-interface.md`, `reuse.lock.json`.
- **Timestamp / author**: {{timestamp}}, Loom builder agent (issue #45).
- **Supersedes**: none
"""
    rc.write_record(EXPERIMENT, rev, INPUTS[:-1], meta, body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
